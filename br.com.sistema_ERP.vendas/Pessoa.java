public class Pessoa {
    private float cpf;
    private String nome;
    private String email;

    public void setCpf(float cpf) {
        this.cpf = cpf;
    }
    public float getCpf() {
        return cpf;
    }
    public void setNome(String nome) {
        this.nome = nome;
    }
    public String getNome() {
        return nome;
    }
    public void setEmail(String email) {
        this.email = email;
    }
    public String getEmail() {
        return email;
    }
    

}
